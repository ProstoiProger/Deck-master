"""Generate the thin per-agent entry files from SKILL.md so there is one source of truth.

    python scripts/build_adapters.py           write AGENTS.md, CLAUDE.md, GEMINI.md and adapters/*
    python scripts/build_adapters.py --check   exit 1 when any generated file is stale

Generated files only point at SKILL.md; they never restate the skill. `scripts/install.py` reuses `pointer()` to write
the same block into other projects, with the real skill path substituted.
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = "<!-- deck-master:begin -->", "<!-- deck-master:end -->"
NOTE = "Generated by scripts/build_adapters.py from SKILL.md. Do not edit by hand."


def frontmatter():
    text = (ROOT / "SKILL.md").read_text(encoding="utf-8").replace("\r\n", "\n")
    head = text.split("---", 2)[1]
    meta = yaml.safe_load(head)
    for key in ("name", "description"):
        if not meta.get(key):
            raise SystemExit(f"SKILL.md frontmatter lacks {key}")
    return meta


def pointer(root="."):
    """The instruction block every agent gets. `root` is where the skill folder is, as seen from the project."""
    def p(rel):
        return rel if root in (".", "") else f"{root.rstrip('/')}/{rel}"
    meta = frontmatter()
    return f"""## {meta['name']}: presentation skill (PPTX and PDF)

Use when the user asks for slides, a deck, a pitch, a presentation, PPTX or PDF slides, or for a review, restyle,
trim or translation of one: assignments, hackathons, datathons, project defenses, research and tech talks.

1. Read `{p('SKILL.md')}` first, then only the reference files it routes to (`{p('references/00-index.md')}` lists all).
2. The deck source is Markdown (see `{p('examples/studybuddy-obsidian/studybuddy.md')}`). Build with the CLI, do not hand-edit the PPTX:
   `python {p('scripts/cli.py')} new|lint|build|preview|trace|timing ...`
3. Deliver only after `lint` shows no Critical or High finding and you have looked at the rendered previews.
4. Every number on a slide needs a `source:`. Never invent numbers; label illustrative ones.
5. Ask before: sending data to external services, overwriting an existing deck, using assets of unclear licence.

First run: `python {p('scripts/install_check.py')} core pptx pdf charts preview` to verify dependencies and fonts.
"""


def managed_block(root):
    return f"{BEGIN}\n{pointer(root)}{END}\n"


def render_all():
    meta = frontmatter()
    desc = " ".join(str(meta["description"]).split())
    files = {}
    files["AGENTS.md"] = f"# AGENTS.md\n\n<!-- {NOTE} -->\n\n{pointer('.')}"
    files["CLAUDE.md"] = f"<!-- {NOTE} -->\n@AGENTS.md\n\nThis folder is also a Claude Code skill: `SKILL.md` is the entry point.\n"
    files["GEMINI.md"] = f"<!-- {NOTE} -->\n@AGENTS.md\n"
    cursor_head = yaml.safe_dump({"description": desc, "globs": "", "alwaysApply": False}, sort_keys=False,
                                 allow_unicode=True, width=10000).strip()
    files["adapters/cursor/deck-master.mdc"] = f"---\n{cursor_head}\n---\n\n<!-- {NOTE} -->\n{pointer('<skill-root>')}"
    files["adapters/copilot/copilot-instructions.md"] = f"<!-- {NOTE} -->\n{pointer('<skill-root>')}"
    files["adapters/windsurf/deck-master.md"] = f"<!-- {NOTE} -->\n{pointer('<skill-root>')}"
    return files


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    files = render_all()
    stale = []
    for rel, text in files.items():
        path = ROOT / rel
        have = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        if "--check" in argv:
            if have != text:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {rel}")
    if "--check" in argv:
        if stale:
            raise SystemExit(f"stale: {', '.join(stale)}; run python scripts/build_adapters.py")
        print("adapters are current")


if __name__ == "__main__":
    main()
