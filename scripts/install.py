"""Install or update deck-master for one or more coding agents.

    python scripts/install.py --agent claude --scope user
    python scripts/install.py --agent cursor --scope project --project path/to/repo
    python scripts/install.py --agent all --scope project --check

Skill-folder agents get the whole folder (claude, codex). Instruction-file agents (cursor, copilot, windsurf,
gemini, agents) get a short pointer file that names the skill folder; with --vendor the folder is copied into the
project first so the pointer is relative and the repo is self-contained.
Existing files are never overwritten blindly: skill folders carry a marker file, shared instruction files
(AGENTS.md, GEMINI.md, copilot-instructions.md) get a managed block between markers, other files are replaced only
when they carry our generated note.

Paths as of 2026-10 (verify against each tool's docs): Claude Code ~/.claude/skills and .claude/skills; Codex
~/.agents/skills and .agents/skills; Cursor .cursor/rules/*.mdc; Copilot .github/copilot-instructions.md; Gemini
GEMINI.md (also ~/.gemini/GEMINI.md); Windsurf .windsurf/rules; AGENTS.md is read by Codex, Cursor, Copilot and others.
"""
import argparse
import os
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_adapters import BEGIN, END, NOTE, ROOT, managed_block, render_all  # noqa: E402

MARKER = ".deck-master-install"
SKILL_NAME = "deck-master"
BASE_IGNORE = shutil.ignore_patterns("build", "__pycache__", ".pytest_cache", ".git", "*.pyc", ".cache")
PRIVATE_DIRS = {"entities", "inspiration"}  # under assets/: downloaded game characters and private reference screenshots


def IGNORE(directory, names):
    """Skip build junk, and never copy downloaded game characters or private screenshots into an install."""
    skip = set(BASE_IGNORE(directory, names))
    d = Path(directory)
    if d.name in PRIVATE_DIRS and d.parent.name == "assets":
        skip |= {n for n in names if n != ".gitkeep"}
    return skip
AGENTS = ["claude", "codex", "cursor", "copilot", "gemini", "windsurf", "agents"]


def home():
    return Path(os.path.expanduser("~"))


def skill_dir_target(agent, scope, project):
    base = {"claude": ".claude/skills", "codex": ".agents/skills"}[agent]
    return (home() if scope == "user" else project) / base / SKILL_NAME


def install_skill_dir(dest, mode, check, dry):
    marker = dest / MARKER
    if Path(dest).resolve().is_relative_to(Path(ROOT).resolve()):
        return (f"SKIP {dest}: the target is inside the skill folder itself ({ROOT}); copying would recurse into its own copy. "
                f"Pass --project <other repo> or use --scope user"), False
    if dest.exists() and not marker.exists() and not (dest.is_symlink()):
        return f"SKIP {dest}: exists and is not a deck-master install (refusing to overwrite)", False
    if check:
        ok = dest.exists() and (dest / "SKILL.md").exists()
        if ok and not dest.is_symlink():
            ok = (dest / "SKILL.md").read_bytes() == (ROOT / "SKILL.md").read_bytes()
        return f"{'ok' if ok else 'DRIFT'} {dest}", ok
    if dry:
        return f"would install {dest} ({mode})", True
    if dest.is_symlink() or dest.exists():
        shutil.rmtree(dest) if dest.is_dir() and not dest.is_symlink() else dest.unlink()
    dest.parent.mkdir(parents=True, exist_ok=True)
    if mode == "link":
        try:
            os.symlink(ROOT, dest, target_is_directory=True)
            return f"linked {dest} -> {ROOT}", True
        except OSError as e:
            print(f"  symlink failed ({e}); falling back to copy")
    shutil.copytree(ROOT, dest, ignore=IGNORE)
    (dest / MARKER).write_text("installed by scripts/install.py\n", encoding="utf-8")
    return f"copied {dest}", True


def rel_root(project, skill_root):
    try:
        return Path(os.path.relpath(skill_root, project)).as_posix()
    except ValueError:
        return Path(skill_root).as_posix()


def write_block(path, block, check, dry):
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else ""
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        new = head + block.rstrip("\n") + tail.lstrip("\n") if False else head + block + tail.lstrip("\n")
    else:
        new = (text.rstrip("\n") + "\n\n" if text.strip() else "") + block
    if check:
        return f"{'ok' if new == text else 'DRIFT'} {path}", new == text
    if dry:
        return f"would update {path}", True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(new, encoding="utf-8", newline="\n")
    return f"updated {path}", True


def write_generated(path, content, check, dry):
    if path.exists():
        have = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        if NOTE not in have and have != content:
            return f"SKIP {path}: exists and was not generated by deck-master", False
        if check:
            return f"{'ok' if have == content else 'DRIFT'} {path}", have == content
    elif check:
        return f"DRIFT {path} (missing)", False
    if dry:
        return f"would write {path}", True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return f"wrote {path}", True


def run(agent, scope, project, mode, vendor, check, dry):
    out = []
    if agent in ("claude", "codex"):
        out.append(install_skill_dir(skill_dir_target(agent, scope, project), mode, check, dry))
        return out
    if scope == "user":
        if agent == "gemini":
            blk = managed_block(Path(ROOT).as_posix())
            out.append(write_block(home() / ".gemini" / "GEMINI.md", blk, check, dry))
        else:
            out.append((f"SKIP {agent}: no user-level file; install with --scope project", False))
        return out
    skill_root = ROOT
    if vendor:
        dest = project / ".deck-master"
        out.append(install_skill_dir(dest, "copy", check, dry))
        skill_root = dest
    root = rel_root(project, skill_root)
    files = render_all()
    if agent == "cursor":
        text = files["adapters/cursor/deck-master.mdc"].replace("<skill-root>", root)
        out.append(write_generated(project / ".cursor" / "rules" / "deck-master.mdc", text, check, dry))
    elif agent == "windsurf":
        text = files["adapters/windsurf/deck-master.md"].replace("<skill-root>", root)
        out.append(write_generated(project / ".windsurf" / "rules" / "deck-master.md", text, check, dry))
    elif agent == "copilot":
        out.append(write_block(project / ".github" / "copilot-instructions.md", managed_block(root), check, dry))
    elif agent == "gemini":
        out.append(write_block(project / "GEMINI.md", managed_block(root), check, dry))
    elif agent == "agents":
        out.append(write_block(project / "AGENTS.md", managed_block(root), check, dry))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--agent", required=True, help=f"one of {AGENTS} or all")
    ap.add_argument("--scope", choices=["user", "project"], default="project")
    ap.add_argument("--project", default=".", help="project folder for --scope project")
    ap.add_argument("--mode", choices=["copy", "link"], default="copy", help="skill-folder agents: copy (default) or symlink")
    ap.add_argument("--vendor", action="store_true", help="copy the skill into <project>/.deck-master and point there")
    ap.add_argument("--check", action="store_true", help="report drift, change nothing; exit 1 on drift")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    agents = AGENTS if a.agent == "all" else [a.agent]
    bad = [x for x in agents if x not in AGENTS]
    if bad:
        raise SystemExit(f"unknown agent {bad}; choose from {AGENTS} or all")
    project = Path(a.project).resolve()
    failed = False
    for agent in agents:
        for msg, ok in run(agent, a.scope, project, a.mode, a.vendor, a.check, a.dry_run):
            print(f"[{agent}] {msg}")
            if not ok and (a.check or msg.startswith("SKIP") and a.agent != "all"):
                failed = True
    if failed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
