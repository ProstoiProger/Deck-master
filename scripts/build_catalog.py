"""Generate references/design/catalog.md from the layout registry and the theme files.

    python scripts/build_catalog.py           write the catalog
    python scripts/build_catalog.py --check   exit 1 if the file on disk is out of date
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from deckkit.core import layout as layout_registry  # noqa: E402
from deckkit.core.paths import references_dir  # noqa: E402
from deckkit.core.theme import contrast_table, load_theme, theme_names  # noqa: E402

TARGET = references_dir() / "design" / "catalog.md"


def render():
    layout_registry.ensure_loaded()
    specs = sorted(layout_registry.LAYOUTS.values(), key=lambda s: (s.family, s.name))
    out = ["# Catalog: layouts and themes", "",
           "Generated by `python scripts/build_catalog.py` from the layout registry and `assets/themes/*.yaml`. Do not edit by hand;",
           "run the script after adding a layout or theme. `python scripts/build_catalog.py --check` fails when this file is stale.",
           "", "## Contents", "", "1. Layouts", "2. Layout inputs", "3. Themes", "", "---", "", "## 1. Layouts", "",
           "| Layout | Family | Max words | Purpose |", "|---|---|---|---|"]
    out += [f"| `{s.name}` | {s.family} | {s.max_words} | {s.purpose} |" for s in specs]
    out += ["", "## 2. Layout inputs", ""]
    for s in specs:
        out += [f"### {s.name}", "", f"Accepts: {s.accepts or 'title only'}", ""]
        if s.example:
            out += ["```markdown", s.example, "```", ""]
    out += ["## 3. Themes", "",
            "| Theme | Mode | bg | surface | primary | accent | text | Text/bg | Muted/bg | Corner | Pattern |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for n in theme_names():
        t = load_theme(n)
        c = dict(contrast_table(t))
        col = t.colors
        out.append(f"| `{n}` | {t.mode} | {col['bg']} | {col['surface']} | {col['primary']} | {col['accent']} | {col['text']} | "
                   f"{c['text on bg']} | {c['muted on bg']} | {t.style['corner']} | {t.style['pattern']} |")
    out += ["", "Ratios are WCAG 2.x contrast. Body text needs 4.5 or more, large text 3 or more.", ""]
    return "\n".join(out)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in argv:
        have = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        if have != text:
            raise SystemExit("catalog.md is out of date; run python scripts/build_catalog.py")
        print("catalog.md is current")
        return
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET} ({len(layout_registry.LAYOUTS)} layouts, {len(theme_names())} themes)")


if __name__ == "__main__":
    main()
